#!/usr/bin/env python3
"""main/portal_html.h: the setup page of kibbl_core (components/kibbl_core/portal.html), gzipped.

The page is sent as it is stored, with Content-Encoding: gzip: a third of the flash.
"""
import gzip
import os

here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, '..', '..', 'components', 'kibbl_core', 'portal.html'), 'rb').read()
data = gzip.compress(html, compresslevel=9, mtime=0)

out = '// generated by tools/portal.py from components/kibbl_core/portal.html\n'
out += '#ifndef PORTAL_HTML_H\n#define PORTAL_HTML_H\n\n'
out += 'static const uint8_t portal_html_gz[] PROGMEM = {\n'
for i in range(0, len(data), 16):
    out += '    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',\n'
out += '};\n\n#endif\n'
open(os.path.join(here, '..', 'main', 'portal_html.h'), 'w', encoding='utf-8').write(out)
