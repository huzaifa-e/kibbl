#!/bin/bash
# Builds kibbl. light (firmware/light) with arduino-cli, the core and libraries of
# main/sketch.yaml. ./build.sh [upload <port>]; the image lands in build/KIBBL-LIGHT.bin.
# CI stamps main/BUILD_INFO.h with create_build_info.sh first, a local build is a WIP one.
set -e
cd "$(dirname "$0")"

version="$(tr -d '[:space:]' < VERSION)"
# a local one follows VERSION; a release stamp of an older number is outdated
if [ ! -f main/BUILD_INFO.h ] || grep -q "generated by build.sh" main/BUILD_INFO.h || ! grep -q -- "-$version-" main/BUILD_INFO.h; then
    printf '// generated by build.sh for a local build\n#ifndef BUILD_INFO_H\n#define BUILD_INFO_H\n#define FW_VERSION "KIBBL-LIGHT-%s-WIP"\n#endif\n' "$version" > main/BUILD_INFO.h
fi

# the setup page of kibbl_core, the same for every product
python3 tools/portal.py

arduino-cli compile --profile light --output-dir build main

if [ "$1" = "upload" ]; then
    # 115200: the adapter is the ESP32-CAM-MB on the controller's pads, without a reset line
    arduino-cli upload --profile light --input-dir build -p "$2" main --upload-property upload.speed=115200
fi
