#!/bin/bash

build_info_file="main/BUILD_INFO.h"

# Get commit hash for dynamic version
if [ -z "$1" ]
then
    echo "Short commit hash must be passed as argument"
    exit 1
fi

# Get branch name for adding branch name to version
# $2 is optional

rm -f $build_info_file

# add comment so humans know some information about this file

echo "// This file is auto-generated by the build pipeline" >> $build_info_file

# add include guard
echo "#ifndef BUILD_INFO_H" >> $build_info_file
echo "#define BUILD_INFO_H" >> $build_info_file

# add dynamic information
echo "#define FW_VERSION \"KIBBL-$1$2\"" >> $build_info_file

# end of include guard
echo "#endif" >> $build_info_file

exit 0
